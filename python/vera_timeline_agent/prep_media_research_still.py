"""Verify a kept Research still and expose it to ordinary still preparation.

The production reader is authenticated loopback HTTP and only requests the
Research ``original`` role.  The reader is injectable so focused tests can use
generated bytes without making an origin request.  Provenance URLs are data,
never fetch targets.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import uuid
from collections.abc import Mapping
from dataclasses import dataclass
from http.client import HTTPException
from io import BytesIO
from pathlib import Path
from typing import Any, Protocol, cast
from urllib.error import HTTPError, URLError
from urllib.parse import quote
from urllib.request import ProxyHandler, Request, build_opener

from PIL import Image, ImageCms, ImageOps

from .build_jobs import BuildJobError, publish_immutable_output
from .build_stage_receipt import hash_file
from .local_media_import import FFmpegDecoder
from .media_preparation import MediaTools
from .narration.models import identity_hash
from .native_image_motion import MAX_STILL_EDGE, MAX_STILL_PIXELS
from .prep_media_research import _bearer_token, _loopback_origin, _NoRedirect

Json = dict[str, Any]

DEFAULT_RESEARCH_ORIGIN = "http://127.0.0.1:43111"
MAX_RESEARCH_STILL_BYTES = 20 * 1024 * 1024
_SHA256 = re.compile(r"^[0-9a-f]{64}$", re.IGNORECASE)
_UUID = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$",
    re.IGNORECASE,
)


class ResearchStillError(ValueError):
    """A Research still transport, authorization, pin, or decode refusal."""


@dataclass(frozen=True)
class KeptStillResponse:
    """The item, manifest, and bytes returned by an authenticated reader."""

    item: Mapping[str, Any]
    manifest: Mapping[str, Any]
    body: bytes
    content_type: str | None = None


class KeptStillReader(Protocol):
    """Small injection point for a trusted kept-byte adapter or focused test."""

    def read(self, snapshot: Mapping[str, Any]) -> KeptStillResponse: ...


@dataclass(frozen=True)
class VerifiedKeptStill:
    snapshot: Json
    body: bytes
    mime_type: str
    original_hash: str


@dataclass(frozen=True)
class MaterializedResearchStill:
    snapshot: Json
    original_path: Path
    source_path: Path
    original_hash: str
    source_hash: str
    source_mime_type: str
    width: int
    height: int


class AuthenticatedKeptStillReader:
    """Read the exact item, manifest, and pinned original from Research #82."""

    def __init__(
        self,
        *,
        origin: str = DEFAULT_RESEARCH_ORIGIN,
        bearer: str | None = None,
        timeout_seconds: float = 35.0,
    ) -> None:
        self.origin = _loopback_origin(origin, "Research origin")
        self.bearer = _bearer_token() if bearer is None else bearer
        self.timeout_seconds = timeout_seconds
        self._opener = build_opener(ProxyHandler({}), _NoRedirect())

    def read(self, snapshot: Mapping[str, Any]) -> KeptStillResponse:
        project_id = _canonical_uuid(
            snapshot.get("researchProjectId"), "Research project ID"
        )
        item_id = _canonical_uuid(snapshot.get("itemId"), "Research still item ID")
        item_path = (
            f"/api/projects/{quote(project_id, safe='')}/items/"
            f"{quote(item_id, safe='')}"
        )
        manifest_path = (
            f"/api/projects/{quote(project_id, safe='')}/stills/"
            f"{quote(item_id, safe='')}/assets"
        )
        first_item = self._json(item_path, "Research still item")
        _verify_item(snapshot, first_item)
        first_manifest = self._json(manifest_path, "Research still manifest")
        original = _verify_manifest(snapshot, first_manifest)
        binary = self._request(
            f"{manifest_path}/original",
            original["mimeType"],
            original["byteCount"],
        )
        if binary[0] in (401, 403):
            raise ResearchStillError(
                "Research refused the credential or project access"
            )
        if binary[0] != 200:
            raise ResearchStillError(
                f"Research kept still original request failed (HTTP {binary[0]})"
            )
        if binary[3] or len(binary[1]) != original["byteCount"]:
            raise ResearchStillError("Research kept still byte count differs from its pin")
        if _content_type(binary[2]) != original["mimeType"]:
            raise ResearchStillError("Research kept still MIME type differs from its pin")
        second_item = self._json(item_path, "Research still item")
        second_manifest = self._json(manifest_path, "Research still manifest")
        if first_item != second_item or first_manifest != second_manifest:
            raise ResearchStillError(
                "Research still changed while its kept bytes were read"
            )
        return KeptStillResponse(
            item=first_item,
            manifest=first_manifest,
            body=binary[1],
            content_type=binary[2],
        )

    def _json(self, path: str, label: str) -> Json:
        status, body, _content_type, oversized = self._request(
            path, "application/json", 256 * 1024
        )
        if oversized:
            raise ResearchStillError(f"{label} exceeds its size limit")
        if status in (401, 403):
            raise ResearchStillError(
                "Research refused the credential or project access"
            )
        if status != 200:
            raise ResearchStillError(f"{label} request failed (HTTP {status})")
        try:
            value = json.loads(body)
        except (UnicodeDecodeError, json.JSONDecodeError) as error:
            raise ResearchStillError(f"{label} is not valid JSON") from error
        if not isinstance(value, dict):
            raise ResearchStillError(f"{label} must be a JSON object")
        return cast(Json, value)

    def _request(
        self, path: str, accept: str, max_bytes: int
    ) -> tuple[int, bytes, str | None, bool]:
        request = Request(
            self.origin + path,
            headers={
                "Accept": accept,
                "Authorization": f"Bearer {self.bearer}",
            },
            method="GET",
        )
        try:
            with self._opener.open(request, timeout=self.timeout_seconds) as response:
                return _read_response(response.status, response, max_bytes)
        except HTTPError as error:
            try:
                return _read_response(error.code, error, max_bytes)
            finally:
                error.close()
        except (URLError, TimeoutError, OSError, HTTPException) as error:
            raise ResearchStillError("Research local service request failed") from error


def acquire_research_still(
    snapshot: Mapping[str, Any],
    *,
    reader: KeptStillReader | None = None,
    research_origin: str = DEFAULT_RESEARCH_ORIGIN,
) -> VerifiedKeptStill:
    """Verify the frozen item/version, manifest original pin, and actual bytes."""
    frozen = _validate_snapshot(snapshot)
    source = reader or AuthenticatedKeptStillReader(origin=research_origin)
    try:
        response = source.read(frozen)
    except ResearchStillError:
        raise
    except (OSError, TypeError, ValueError) as error:
        raise ResearchStillError("Research kept still read failed") from error
    if not isinstance(response, KeptStillResponse):
        raise ResearchStillError(
            "Research kept still reader returned an invalid response"
        )
    _verify_item(frozen, response.item)
    original = _verify_manifest(frozen, response.manifest)
    body = response.body
    if not isinstance(body, bytes):
        raise ResearchStillError("Research kept still bytes are invalid")
    if len(body) != original["byteCount"]:
        raise ResearchStillError("Research kept still byte count differs from its pin")
    if len(body) > MAX_RESEARCH_STILL_BYTES:
        raise ResearchStillError("Research kept still exceeds the host byte limit")
    content_type = _content_type(response.content_type)
    if content_type is not None and content_type != original["mimeType"]:
        raise ResearchStillError("Research kept still MIME type differs from its pin")
    digest = hashlib.sha256(body).hexdigest()
    if digest != original["sha256"]:
        raise ResearchStillError(
            "Research kept still bytes differ from their pinned SHA-256"
        )
    _verify_image(body, original)
    return VerifiedKeptStill(
        snapshot=frozen,
        body=body,
        mime_type=original["mimeType"],
        original_hash=f"sha256:{digest}",
    )


def materialize_research_still(
    snapshot: Mapping[str, Any],
    media_root: Path,
    *,
    reader: KeptStillReader | None = None,
    research_origin: str = DEFAULT_RESEARCH_ORIGIN,
) -> MaterializedResearchStill:
    """Publish verified bytes under the project Media root.

    WebP is converted to a deterministic RGB PNG.  The upstream and local
    hashes stay separate in the returned value and in immutable path names.
    """
    verified = acquire_research_still(
        snapshot, reader=reader, research_origin=research_origin
    )
    root = _safe_root(media_root)
    digest = verified.original_hash.removeprefix("sha256:")
    suffix = {
        "image/jpeg": ".jpg",
        "image/png": ".png",
        "image/webp": ".webp",
    }[verified.mime_type]
    folder = _safe_path(
        root
        / "Research Stills"
        / verified.snapshot["researchProjectId"]
        / verified.snapshot["itemId"]
    )
    original_path = _safe_path(folder / f"original-{digest}{suffix}")
    _publish_same(original_path, verified.body)
    if verified.mime_type == "image/webp":
        source_bytes = _normalize_webp(verified.body, verified.snapshot["original"])
        source_path = _safe_path(
            folder / f"source-{hashlib.sha256(source_bytes).hexdigest()}.png"
        )
        source_mime = "image/png"
    else:
        source_bytes = verified.body
        source_path = original_path
        source_mime = verified.mime_type
    _publish_same(source_path, source_bytes)
    width, height = _dimensions(source_bytes, source_mime)
    if (width, height) != (
        verified.snapshot["original"]["width"],
        verified.snapshot["original"]["height"],
    ):
        raise ResearchStillError(
            "Materialized Research still dimensions differ from their pin"
        )
    return MaterializedResearchStill(
        snapshot=verified.snapshot,
        original_path=original_path,
        source_path=source_path,
        original_hash=verified.original_hash,
        source_hash=f"sha256:{hashlib.sha256(source_bytes).hexdigest()}",
        source_mime_type=source_mime,
        width=width,
        height=height,
    )


def bind_research_still_descriptor(
    descriptor: Mapping[str, Any],
    materialized: MaterializedResearchStill,
    *,
    tools: MediaTools,
    frame_rate: Mapping[str, Any],
) -> Json:
    """Create the ordinary one-frame local-import descriptor."""
    result = dict(descriptor)
    media_reference_id = result.get("mediaReferenceId")
    payload_id = result.get("payloadId")
    if (
        not isinstance(media_reference_id, str)
        or _UUID.fullmatch(media_reference_id) is None
        or not isinstance(payload_id, str)
        or _UUID.fullmatch(payload_id) is None
        or not isinstance(result.get("owner"), Mapping)
    ):
        raise ResearchStillError("Research still descriptor identity is invalid")
    numerator, denominator = frame_rate.get("numerator"), frame_rate.get("denominator")
    if (
        type(numerator) is not int
        or type(denominator) is not int
        or numerator <= 0
        or denominator <= 0
    ):
        raise ResearchStillError("Research still target rate is invalid")
    fd = os.open(
        materialized.source_path,
        os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK,
    )
    try:
        facts = FFmpegDecoder(ffprobe=tools.ffprobe, ffmpeg=tools.ffmpeg).decode(
            fd, "image"
        )
    except (OSError, ValueError) as error:
        raise ResearchStillError(
            "Materialized Research still failed image probing"
        ) from error
    finally:
        os.close(fd)
    codec = (
        "mjpeg"
        if materialized.source_path.suffix.lower() in {".jpg", ".jpeg"}
        else "png"
    )
    probe = {
        "kind": "image",
        "demuxer": "image2pipe",
        "codec": codec,
        "width": facts.width,
        "height": facts.height,
        "frames": 1,
    }
    if facts.probe_hash != identity_hash(probe):
        raise ResearchStillError("Materialized Research still probe is not stable")
    if f"sha256:{hash_file(materialized.source_path)}" != materialized.source_hash:
        raise ResearchStillError("Materialized Research still changed on disk")
    rate = {"numerator": numerator, "denominator": denominator}
    source_snapshot = {
        "system": "local_import",
        "snapshotId": materialized.snapshot["itemId"],
        "version": materialized.snapshot["itemVersion"],
        "packageId": media_reference_id,
        "contentHash": materialized.source_hash,
        "probeHash": facts.probe_hash,
    }
    source_frame_map = {
        "packageFrameZeroLogicalFrame": 0,
        "packageVideoPtsOrigin": {"numerator": 0, "denominator": 1},
        "loggedTimeAtPackageFrameZero": {"numerator": 0, "denominator": 1},
        "decodedPackageFrameRate": rate,
        "decodedPackageFrameCount": 1,
        "packageVideoTimeBase": {"numerator": denominator, "denominator": numerator},
        "sourceAudioStreamMappings": [],
        "descriptorHash": identity_hash({"snapshot": source_snapshot, "probe": probe}),
        "probeHash": facts.probe_hash,
    }
    result.update(
        sourceSnapshot=source_snapshot,
        logicalSourceBounds={"startFrame": 0, "endFrame": 1, "frameRate": rate},
        sourceFrameMap=source_frame_map,
        occurrenceSourceInFrame=0,
        selectedSourceRange=None,
        preparedMediaRequirementKey=None,
    )
    return result


def _validate_snapshot(snapshot: Mapping[str, Any]) -> Json:
    if not isinstance(snapshot, Mapping):
        raise ResearchStillError("Research still snapshot is invalid")
    project_id = _canonical_uuid(
        snapshot.get("researchProjectId"), "Research project ID"
    )
    item_id = _canonical_uuid(snapshot.get("itemId"), "Research still item ID")
    source_id = _canonical_uuid(snapshot.get("sourceId"), "Research still source ID")
    version = snapshot.get("itemVersion")
    title = snapshot.get("title")
    original = snapshot.get("original")
    if (
        type(version) is not int
        or version <= 0
        or not isinstance(title, str)
        or not title.strip()
        or not isinstance(original, Mapping)
        or not isinstance(snapshot.get("provenance"), Mapping)
    ):
        raise ResearchStillError("Research still snapshot is incomplete")
    _validate_asset(original)
    return cast(
        Json,
        {
            **dict(snapshot),
            "researchProjectId": project_id,
            "itemId": item_id,
            "sourceId": source_id,
            "title": title.strip(),
            "original": {**dict(original), "sha256": str(original["sha256"]).lower()},
        },
    )


def _verify_item(snapshot: Mapping[str, Any], item: Mapping[str, Any]) -> None:
    if (
        not isinstance(item, Mapping)
        or item.get("kind") != "still"
        or _lower_uuid(item.get("projectId")) != snapshot["researchProjectId"]
        or _lower_uuid(item.get("id")) != snapshot["itemId"]
        or _lower_uuid(item.get("sourceId")) != snapshot["sourceId"]
        or item.get("version") != snapshot["itemVersion"]
        or type(item.get("version")) is not int
    ):
        raise ResearchStillError("Research saved still identity or version changed")
    content = item.get("content")
    title = content.get("title") if isinstance(content, Mapping) else None
    if title is None:
        title = "Saved still"
    if (
        not isinstance(content, Mapping)
        or not isinstance(title, str)
        or title.strip() != snapshot["title"]
    ):
        raise ResearchStillError("Research saved still metadata changed")
    for key in ("credit", "licence", "usageNote"):
        if content.get(key) != snapshot.get(key):
            raise ResearchStillError(f"Research saved still {key} changed")


def _verify_manifest(snapshot: Mapping[str, Any], manifest: Mapping[str, Any]) -> Json:
    original = _manifest_asset(manifest)
    frozen = cast(Mapping[str, Any], snapshot["original"])
    for key in ("versionId", "sha256", "byteCount", "mimeType", "width", "height"):
        expected = str(frozen[key]).lower() if key == "sha256" else frozen[key]
        if original[key] != expected:
            raise ResearchStillError(f"Research kept still original {key} changed")
    if manifest.get("provenance") != snapshot.get("provenance"):
        raise ResearchStillError("Research kept still provenance changed")
    return original


def _manifest_asset(manifest: Mapping[str, Any]) -> Json:
    assets = manifest.get("assets")
    if not isinstance(assets, Mapping) or not isinstance(
        assets.get("original"), Mapping
    ):
        raise ResearchStillError("Research kept still manifest has no original asset")
    asset = cast(Json, dict(cast(Mapping[str, Any], assets["original"])))
    _validate_asset(asset)
    asset["sha256"] = str(asset["sha256"]).lower()
    return asset


def _validate_asset(asset: Mapping[str, Any]) -> None:
    if (
        not isinstance(asset.get("versionId"), str)
        or not asset["versionId"].strip()
        or len(asset["versionId"]) > 1024
        or not isinstance(asset.get("sha256"), str)
        or _SHA256.fullmatch(asset["sha256"]) is None
        or type(asset.get("byteCount")) is not int
        or not 1 <= asset["byteCount"] <= MAX_RESEARCH_STILL_BYTES
        or type(asset.get("width")) is not int
        or type(asset.get("height")) is not int
        or not 1 <= asset["width"] <= MAX_STILL_EDGE
        or not 1 <= asset["height"] <= MAX_STILL_EDGE
        or asset["width"] * asset["height"] > MAX_STILL_PIXELS
        or asset.get("mimeType") not in {"image/jpeg", "image/png", "image/webp"}
    ):
        raise ResearchStillError("Research kept still original asset is invalid")


def _verify_image(body: bytes, asset: Mapping[str, Any]) -> None:
    formats = {"image/jpeg": "JPEG", "image/png": "PNG", "image/webp": "WEBP"}
    try:
        with Image.open(BytesIO(body)) as image:
            if image.format != formats[asset["mimeType"]] or image.size != (
                asset["width"],
                asset["height"],
            ):
                raise ResearchStillError(
                    "Research kept still format or dimensions differ from their pin"
                )
            if getattr(image, "n_frames", 1) != 1:
                raise ResearchStillError("Research kept still is animated")
    except ResearchStillError:
        raise
    except (OSError, ValueError) as error:
        raise ResearchStillError(
            "Research kept still bytes are not a decodable image"
        ) from error


def _normalize_webp(body: bytes, asset: Mapping[str, Any]) -> bytes:
    try:
        with Image.open(BytesIO(body), formats=["WEBP"]) as image:
            if image.format != "WEBP" or getattr(image, "n_frames", 1) != 1:
                raise ResearchStillError(
                    "Research kept WebP still must contain one frame"
                )
            if image.mode in {"RGBA", "LA"} or "transparency" in image.info:
                raise ResearchStillError("Research kept WebP still must be opaque")
            ImageOps.exif_transpose(image, in_place=True)
            output = image.convert("RGB")
            icc_profile = image.info.get("icc_profile")
            if isinstance(icc_profile, bytes) and icc_profile:
                try:
                    profile = ImageCms.ImageCmsProfile(BytesIO(icc_profile))
                    if profile.profile.xcolor_space != "RGB ":
                        raise ResearchStillError(
                            "Research WebP ICC profile must be RGB"
                        )
                    converted = ImageCms.profileToProfile(
                        output,
                        profile,
                        ImageCms.createProfile("sRGB"),
                        outputMode="RGB",
                    )
                    if converted is None:
                        raise ResearchStillError("Research WebP ICC conversion failed")
                    output = converted
                except ResearchStillError:
                    raise
                except (ImageCms.PyCMSError, OSError, TypeError, ValueError) as error:
                    raise ResearchStillError(
                        "Research WebP ICC conversion failed"
                    ) from error
            output.info.clear()
            target = BytesIO()
            output.save(target, format="PNG")
            result = target.getvalue()
    except ResearchStillError:
        raise
    except (OSError, ValueError) as error:
        raise ResearchStillError("Research WebP still conversion failed") from error
    with Image.open(BytesIO(result)) as normalized:
        if normalized.size != (asset["width"], asset["height"]):
            raise ResearchStillError("Research WebP conversion changed dimensions")
    return result


def _dimensions(body: bytes, mime_type: str) -> tuple[int, int]:
    formats = {"image/jpeg": "JPEG", "image/png": "PNG"}
    try:
        with Image.open(BytesIO(body)) as image:
            if image.format != formats[mime_type]:
                raise ValueError
            return image.size
    except (OSError, ValueError, KeyError) as error:
        raise ResearchStillError(
            "Materialized Research still cannot be decoded"
        ) from error


def _publish_same(path: Path, body: bytes) -> None:
    _safe_path(path)
    try:
        publish_immutable_output(path, body)
    except BuildJobError as error:
        raise ResearchStillError(
            "Project Research still copy has different immutable bytes"
        ) from error
    if hash_file(path) != hashlib.sha256(body).hexdigest():
        raise ResearchStillError(
            "Project Research still copy changed during publication"
        )


def _safe_root(path: Path) -> Path:
    root = _safe_path(path)
    if root == Path(root.anchor):
        raise ResearchStillError("Research still media root must be project-local")
    root.mkdir(parents=True, exist_ok=True)
    if not root.is_dir():
        raise ResearchStillError("Research still media root is not a directory")
    return root


def _safe_path(path: Path) -> Path:
    absolute = Path(path).absolute()
    if ".." in absolute.parts or any(
        part.is_symlink() for part in (absolute, *absolute.parents)
    ):
        raise ResearchStillError("Research still path cannot contain symbolic links")
    return absolute


def _canonical_uuid(value: Any, label: str) -> str:
    if not isinstance(value, str) or _UUID.fullmatch(value) is None:
        raise ResearchStillError(f"{label} is invalid")
    try:
        return str(uuid.UUID(value)).lower()
    except ValueError as error:
        raise ResearchStillError(f"{label} is invalid") from error


def _lower_uuid(value: Any) -> str | None:
    return value.lower() if isinstance(value, str) and _UUID.fullmatch(value) else None


def _read_response(
    status: int, response: Any, max_bytes: int
) -> tuple[int, bytes, str | None, bool]:
    length = response.headers.get("Content-Length")
    if length is not None:
        try:
            if int(length) > max_bytes:
                return status, b"", response.headers.get("Content-Type"), True
        except ValueError:
            raise ResearchStillError(
                "Research returned an invalid content length"
            ) from None
    body = response.read(max_bytes + 1)
    return (
        status,
        body[:max_bytes],
        response.headers.get("Content-Type"),
        len(body) > max_bytes,
    )


def _content_type(value: str | None) -> str | None:
    return value.split(";", 1)[0].strip().lower() if value else None
