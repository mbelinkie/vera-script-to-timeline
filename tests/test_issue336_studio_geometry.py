def test_real_studio_evidence_has_full_decodes_and_exact_reopen() -> None:
    evidence = json.loads(_RUN5.read_text())
    assert evidence["native_app"] == "21.1.1.10"
    assert evidence["frame_rate"] == 24
    assert evidence["output_size"] == [1280, 720]
    assert evidence["timeline_profile"] == {
        "width": 1920,
        "height": 1080,
        "frame_rate": 24,
    }
    assert evidence["rendered_cover_endpoint_right_mid_rgb"] == [0, 0, 0]
    assert all(len(v) == 64 for v in evidence["source_sha256"].values())
    cases = evidence["case_results"]
    assert len(cases) == 11
    assert evidence["reopened"]["timelineCount"] == len(cases)
    assert evidence["reopened"]["names"] == list(cases)
    assert evidence["reopened"]["durations"] == [
        case["frames"] for case in cases.values()
    ]
    for case in cases.values():
        assert len(case["decoded_sha256"]) == 64
        assert len(case["witnesses"]) == 5
        assert list(map(int, case["witnesses"])) == sorted(map(int, case["witnesses"]))

    baseline = cases["square-none-48"]
    assert len({tuple(case["magenta"]) for case in baseline["witnesses"].values()}) == 1
    assert all(
        all(case[color] is not None for color in ("red", "green", "blue", "yellow"))
        for case in baseline["witnesses"].values()
    )
    animated = cases["square-motion-48"]
    assert len({tuple(case["magenta"]) for case in animated["witnesses"].values()}) == 5
    assert all(
        case["red"] is None and case["green"] is None
        for case in animated["witnesses"].values()
    )
    for mode in ("in", "out", "both"):
        assert (
            cases[f"square-ease-{mode}-48"]["decoded_sha256"]
            == animated["decoded_sha256"]
        )


@pytest.mark.parametrize(
    ("source_size", "framing", "decoded_centroids"),
    [
        (
            (1000, 1000),
            "contain",
            [(866, 180), (824, 177), (789, 172), (758, 171), (731, 168)],
        ),
        (
            (1600, 900),
            "contain",
            [(1041, 180), (968, 176), (903, 174), (848, 170), (802, 168)],
        ),
        (
            (900, 1600),
            "contain",
            [(766, 180), (742, 176), (723, 174), (705, 171), (692, 168)],
        ),
        (
            (1000, 1000),
            "cover",
            [(1041, 40), (968, 34), (904, 28), (849, 26), (803, 22)],
        ),
    ],
)
def test_raster_measured_focus_projection_three_aspect_ratios_and_cover(
    source_size: tuple[int, int],
    framing: str,
    decoded_centroids: list[tuple[int, int]],
) -> None:
    """Each measured point is a centroid of source marker (.75,.30)."""
    case_name = {
        ((1000, 1000), "contain"): "square-motion-48",
        ((1600, 900), "contain"): "wide-motion-48",
        ((900, 1600), "contain"): "tall-motion-48",
        ((1000, 1000), "cover"): "square-cover-48",
    }[(source_size, framing)]
    actual = json.loads(_RUN5.read_text())["case_results"][case_name]["witnesses"]
    assert [actual[str(frame)]["magenta"] for frame in (0, 12, 24, 36, 47)] == [
        list(point) for point in decoded_centroids
    ]
    for frame, observed in zip((0, 12, 24, 36, 47), decoded_centroids, strict=True):
        p = frame / 48
        predicted = native_projected_point(
            source_size=source_size,
            timeline_size=(1280, 720),
            framing=framing,
            source_point=(0.75, 0.30),
            center=(0.12 * p, -0.08 * p),
            native_scale=0.8 + (1.05 - 0.8) * p,
        )
        assert predicted == pytest.approx(observed, abs=4)


@pytest.mark.parametrize(
    ("duration", "last_center"),
    [(24, (734, 168)), (48, (731, 168)), (96, (730, 168)), (144, (730, 168))],
)
def test_native_interpolation_uses_frame_over_duration_not_last_frame(
    duration: int, last_center: tuple[int, int]
) -> None:
    p = (duration - 1) / duration
    actual = json.loads(_RUN5.read_text())["case_results"][f"square-motion-{duration}"][
        "witnesses"
    ][str(duration - 1)]["magenta"]
    assert actual == list(last_center)
    projected = native_projected_point(
        source_size=(1000, 1000),
        timeline_size=(1280, 720),
        framing="contain",
        source_point=(0.75, 0.30),
        center=(0.12 * p, -0.08 * p),
        native_scale=0.8 + 0.25 * p,
    )
    assert projected == pytest.approx(last_center, abs=3)


