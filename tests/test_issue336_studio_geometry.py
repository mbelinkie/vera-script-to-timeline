def test_focus_native_inverse_and_strict_bounded_admission() -> None:
    assert native_endpoint_from_focus({"focusX": 0.62, "focusY": 0.58, "scale": 1.25})[
        0
    ] == pytest.approx((0.12, -0.08))
    assert native_endpoint_from_focus({"focusX": 0.62, "focusY": 0.58, "scale": 1.25})[
        1
    ] == pytest.approx(0.8)
    assert native_endpoint_from_focus({"focusX": 0.5, "focusY": 0.5, "scale": 1.0}) == (
        (0.0, 0.0),
        1.0,
    )


